// Parses news-world.md (yearly markdown tables 2019–2026) into
// src/app/noticias/worldNews.ts for the /noticias timeline.
import { readFileSync, writeFileSync } from "node:fs";

const SRC = new URL("../news-world.md", import.meta.url);
const OUT = new URL("../src/app/noticias/worldNews.ts", import.meta.url);

const MONTHS = {
  january: 1, february: 2, march: 3, april: 4, may: 5, june: 6,
  july: 7, august: 8, september: 9, october: 10, november: 11, december: 12,
};

function parseDate(raw, year) {
  const t = raw.toLowerCase();
  const m = t.match(/(january|february|march|april|may|june|july|august|september|october|november|december)\s*(\d{1,2})?/);
  if (!m) return `${year}-06-30`; // "Throughout <year>"
  const month = MONTHS[m[1]];
  const day = m[2] ? Number(m[2]) : 15;
  return `${year}-${String(month).padStart(2, "0")}-${String(day).padStart(2, "0")}`;
}

// Explicit overrides for events the keyword rules misjudge
const OVERRIDES = [
  [/sri lanka/i, "politics"],
  [/ai investment reshapes/i, "economics"],
  [/deepseek/i, "economics"],
  [/pandora papers/i, "economics"],
  [/launch major military strikes/i, "politics"],
  [/strait of hormuz crisis/i, "economics"],
];

function categorize(text) {
  for (const [re, cat] of OVERRIDES) if (re.test(text)) return cat;
  const t = text.toLowerCase();
  if (/(pope|vatican|notre-dame|cathedral|catholic)/.test(t)) return "religion";
  if (/(trade war|tariff|inflation|stock market|markets crash|oil price|silicon valley bank|banking|ftx|crypto|imf|supply chain|rare-earth|trade agreement|trade bloc|global economy|energy shock|energy crisis)/.test(t)) return "economics";
  if (/(black hole|telescope|spacex|nasa|chandrayaan|satellite|fusion|artemis|webb|spaceflight|solar probe|chatgpt|gpt-4|crowdstrike|anti-satellite|virgin galactic|moon landing)/.test(t)) return "science";
  if (/(climate|wildfire|bushfire|hurricane|typhoon|earthquake|flood|rainforest fires|hottest year|cop2\d|cop3\d)/.test(t)) return "climate";
  if (/(olympic|world cup|fifa|world population|queen elizabeth|covid|pandemic|vaccin|omicron|variant of concern|coronavirus|health emergency|submersible)/.test(t)) return "society";
  return "politics";
}

const lines = readFileSync(SRC, "utf8").split("\n");
let year = 2018;
const events = [];

for (const line of lines) {
  if (!line.startsWith("|")) continue;
  const cells = line.split("|").map(c => c.trim());
  // cells[0] is empty (leading pipe): [_, rank, date, event, why, _]
  if (cells[1] === "Rank") { year += 1; continue; }
  if (/^-+$/.test(cells[1] ?? "")) continue;
  const [, , rawDate, rawEvent, rawWhy] = cells;
  if (!rawEvent) continue;
  const headline = rawEvent.replace(/\*\*/g, "").trim();
  const summary = (rawWhy ?? "").trim();
  events.push({
    date: parseDate(rawDate ?? "", year),
    headline,
    summary,
    category: categorize(`${headline} ${summary}`),
  });
}

events.sort((a, b) => a.date.localeCompare(b.date));
const out = events.map((e, i) => ({ id: i + 1, ...e }));

const ts = `// Generated by scripts/parse-news.mjs from news-world.md — do not edit by hand.
// Re-run: node scripts/parse-news.mjs
import type { NewsMarker } from "../newsTypes";

export const WORLD_NEWS: NewsMarker[] = ${JSON.stringify(out, null, 2)};
`;
writeFileSync(OUT, ts);
console.log(`Wrote ${out.length} events (${out[0].date} → ${out[out.length - 1].date})`);
const counts = {};
for (const e of out) counts[e.category] = (counts[e.category] ?? 0) + 1;
console.log(counts);
